-- local function to check if a quest is completed and return a formatted string
local function ISQ(quest_id)
	local str = ""
	local isCompleted = false
	if (not quest_id) then return str end

	isCompleted = IsQuestFlaggedCompleted(quest_id)

	if (isCompleted) then
		str = ""
	else
		str = GREY..L_PAREN..UNAVAILABLE..R_PAREN
	end

	return str
end


